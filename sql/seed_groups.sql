-- =====================================================
-- SEED: Связи учитель-ученик, группы и состав групп
-- Каждый учитель ведет 4 учеников
-- В группе у каждого учителя 3 ученика (один - вне группы)
-- Идемпотентный скрипт с синхронизацией счетчиков
-- =====================================================

BEGIN;

-- ------------------------------------------------------------------
-- 1. СВЯЗИ УЧИТЕЛЬ-УЧЕНИК (teacher_student)
-- teacher_1 (id=1): ученики 6,7,8,9
-- teacher_2 (id=2): ученики 10,11,12,13
-- teacher_3 (id=3): ученики 14,15,16,17
-- teacher_4 (id=4): ученики 18,19,20,21
-- teacher_5 (id=5): ученики 22,23,24,25
-- 
-- Всего: 5 учителей × 4 ученика = 20 записей
-- ------------------------------------------------------------------
INSERT INTO public.teacher_student (teacher_id, student_id, status, is_deleted, created_at, last_update_at)
VALUES
    -- Учитель 1 (id=1) - ученики 6,7,8,9
    (1, 6,  1, false, now(), now()),
    (1, 7,  1, false, now(), now()),
    (1, 8,  1, false, now(), now()),
    (1, 9,  1, false, now(), now()),
    
    -- Учитель 2 (id=2) - ученики 10,11,12,13
    (2, 10, 1, false, now(), now()),
    (2, 11, 1, false, now(), now()),
    (2, 12, 1, false, now(), now()),
    (2, 13, 1, false, now(), now()),
    
    -- Учитель 3 (id=3) - ученики 14,15,16,17
    (3, 14, 1, false, now(), now()),
    (3, 15, 1, false, now(), now()),
    (3, 16, 1, false, now(), now()),
    (3, 17, 1, false, now(), now()),
    
    -- Учитель 4 (id=4) - ученики 18,19,20,21
    (4, 18, 1, false, now(), now()),
    (4, 19, 1, false, now(), now()),
    (4, 20, 1, false, now(), now()),
    (4, 21, 1, false, now(), now()),
    
    -- Учитель 5 (id=5) - ученики 22,23,24,25
    (5, 22, 1, false, now(), now()),
    (5, 23, 1, false, now(), now()),
    (5, 24, 1, false, now(), now()),
    (5, 25, 1, false, now(), now())
ON CONFLICT (teacher_id, student_id) DO UPDATE SET
    status = EXCLUDED.status,
    is_deleted = EXCLUDED.is_deleted,
    last_update_at = now()
WHERE public.teacher_student.status IS DISTINCT FROM EXCLUDED.status;

-- ------------------------------------------------------------------
-- 2. ГРУППЫ (group)
-- Каждый учитель создает по 1 группе, объединяющей 3 учеников
-- Четвертый ученик остается вне группы (индивидуальное обучение)
-- subject_id = 1 (Русский язык)
-- ------------------------------------------------------------------
INSERT INTO public.group (id, teacher_id, name, subject_id, is_deleted, created_at, last_update_at)
VALUES
    (1, 1, 'Русский язык - Группа 1', 1, false, now(), now()),
    (2, 2, 'Русский язык - Группа 2', 1, false, now(), now()),
    (3, 3, 'Русский язык - Группа 3', 1, false, now(), now()),
    (4, 4, 'Русский язык - Группа 4', 1, false, now(), now()),
    (5, 5, 'Русский язык - Группа 5', 1, false, now(), now())
ON CONFLICT (id) DO UPDATE SET
    name = EXCLUDED.name,
    teacher_id = EXCLUDED.teacher_id,
    subject_id = EXCLUDED.subject_id,
    last_update_at = now(),
    is_deleted = false
WHERE public.group.name IS DISTINCT FROM EXCLUDED.name;

-- ------------------------------------------------------------------
-- 3. СОСТАВ ГРУПП (student_group_student)
-- В каждой группе по 3 ученика (4-й ученик каждого учителя - вне группы)
-- 
-- Группа 1 (учитель 1): ученики 6,7,8 (ученик 9 - вне группы)
-- Группа 2 (учитель 2): ученики 10,11,12 (ученик 13 - вне группы)
-- Группа 3 (учитель 3): ученики 14,15,16 (ученик 17 - вне группы)
-- Группа 4 (учитель 4): ученики 18,19,20 (ученик 21 - вне группы)
-- Группа 5 (учитель 5): ученики 22,23,24 (ученик 25 - вне группы)
-- ------------------------------------------------------------------
INSERT INTO public.student_group_student (group_id, student_id)
VALUES
    -- Группа 1 (учитель 1) - 3 ученика, student_9 вне группы
    (1, 6),
    (1, 7),
    (1, 8),
    
    -- Группа 2 (учитель 2) - 3 ученика, student_13 вне группы
    (2, 10),
    (2, 11),
    (2, 12),
    
    -- Группа 3 (учитель 3) - 3 ученика, student_17 вне группы
    (3, 14),
    (3, 15),
    (3, 16),
    
    -- Группа 4 (учитель 4) - 3 ученика, student_21 вне группы
    (4, 18),
    (4, 19),
    (4, 20),
    
    -- Группа 5 (учитель 5) - 3 ученика, student_25 вне группы
    (5, 22),
    (5, 23),
    (5, 24)
ON CONFLICT (group_id, student_id) DO NOTHING;

-- ------------------------------------------------------------------
-- 4. СИНХРОНИЗАЦИЯ СЧЕТЧИКОВ SEQUENCE
-- ------------------------------------------------------------------
-- Для teacher_student (id генерируется автоматически)
SELECT setval(
    pg_get_serial_sequence('teacher_student', 'id'),
    COALESCE((SELECT MAX(id) FROM public.teacher_student), 0) + 1,
    false
);

-- Для group (id у нас фиксированные 1-5, счетчик на 6)
SELECT setval(
    pg_get_serial_sequence('"group"', 'id'),
    COALESCE((SELECT MAX(id) FROM public."group"), 0) + 1,
    false
);

COMMIT;

-- =====================================================
